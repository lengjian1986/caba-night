const jaToZh = Object.entries(zhToJa).reduce(
    (map, [zh, ja]) => {
        map[ja] = zh
        return map
    },
    {} as Record<string, string>
)

export const t = (text: unknown, language: AdminLanguage = 'zh') => {
    const value = String(text ?? '')
    if (language === 'ja') {
        return zhToJa[value] || value
    }
    return jaToZh[value] || value
}

export const translateInlineText = (text: string, language: AdminLanguage) => {
    const trimmed = text.trim()
    if (!trimmed) return text

    let translated = t(trimmed, language)
    if (translated === trimmed && trimmed.includes('/')) {
        translated = trimmed
            .split('/')
            .map((item) => t(item, language))
            .join('/')
    }
    if (translated === trimmed && language === 'ja') {
        translated = trimmed
            .replace(/^最大(\d+)人$/, '最大$1人')
            .replace(/^折扣：/, '割引：')
            .replace(/^例如 /, '例：')
            .replace(/ \/ 最大(\d+)人$/, ' / 最大$1人')
            .replace(/ \/ 时间范围$/, ' / 期間指定')
            .replace(/ \/ 次数限定$/, ' / 回数限定')
    }
    if (translated === trimmed) return text

    const prefix = text.match(/^\s*/)?.[0] ?? ''
    const suffix = text.match(/\s*$/)?.[0] ?? ''
    return `${prefix}${translated}${suffix}`
}
